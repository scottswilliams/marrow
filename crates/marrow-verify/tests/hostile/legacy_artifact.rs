#[test]
fn pre_containment_nominal_image_is_refused() {
    let refusal = marrow_verify::verify(NOMINAL_RECORD_IMAGE)
        .expect_err("the old nominal-bearing artifact must not enter execution");
    assert_eq!(refusal.phase(), marrow_verify::VerifyPhase::Envelope);
}

#[test]
fn relabeling_an_old_image_preserves_its_invalid_digest() {
    let mut relabeled = NOMINAL_RECORD_IMAGE.to_vec();
    relabeled[4] = marrow_image::IMAGE_FORMAT_VERSION;
    let refusal =
        marrow_verify::verify(&relabeled).expect_err("a header edit cannot convert a legacy image");
    assert_eq!(refusal.phase(), marrow_verify::VerifyPhase::Envelope);
}
